#!/usr/bin/env node
/**
 * Embeds report template binaries (.docx / .pptx) as base64 strings in a
 * generated TS module. Templates are fetched at build time and shipped inside
 * the bundle so the app never needs fetch() at runtime (which fails under
 * file:// anyway).
 *
 * Usage: `node scripts/embed-templates.mjs`
 */
import { readFileSync, mkdirSync, writeFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { join, resolve } from "node:path";

const templatesDir = resolve(process.cwd(), "templates");
const outFile = resolve(process.cwd(), "src/export/templates.generated.ts");

const candidates = [];
if (existsSync(templatesDir)) {
  for (const entry of readdirSync(templatesDir)) {
    const full = join(templatesDir, entry);
    if (statSync(full).isDirectory()) {
      for (const sub of readdirSync(full)) {
        const subFull = join(full, sub);
        if (/\.(docx|pptx)$/i.test(sub)) candidates.push(subFull);
      }
    } else if (/\.(docx|pptx)$/i.test(entry)) {
      candidates.push(full);
    }
  }
}

/** Simple fingerprint: version from path for cache-busting keyed embeds. */
const records = candidates.map((file) => {
  const base = file.replace(/\\/g, "/").split("/").slice(-2).join("/");
  const data = readFileSync(file);
  return { rel: base, base64: data.toString("base64"), bytes: data.length };
});

if (records.length === 0) {
  console.warn("[embed-templates] No .docx/.pptx templates found. Emitting empty registry.");
}

const body = `// AUTO-GENERATED by scripts/embed-templates.mjs. Do not edit by hand.
// Contains base64-encoded report templates shipped inside the bundle so the
// app never performs a fetch() for its official templates.
export type TemplateAsset = { rel: string; bytes: number; base64: string };
export const templates: TemplateAsset[] = ${JSON.stringify(records, null, 2)};

export function getTemplate(rel: string): TemplateAsset | undefined {
  return templates.find((t) => t.rel === rel);
}
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body, "utf8");
console.log(`[embed-templates] Wrote ${records.length} template(s) (${records.reduce((s, r) => s + r.bytes, 0)} bytes) -> ${outFile}`);

function dirname(p) {
  return p.slice(0, p.lastIndexOf("/"));
}